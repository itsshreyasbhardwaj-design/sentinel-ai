/** Index by `ecosystem:package` so lookup is O(1) per dependency. */
export const ADVISORY_INDEX: Map<string, Advisory[]> = BUNDLED_ADVISORIES.reduce(
  (index, advisory) => {
    const key = `${advisory.ecosystem}:${advisory.package.toLowerCase()}`;
    const list = index.get(key) ?? [];
    list.push(advisory);
    index.set(key, list);
    return index;
  },
  new Map<string, Advisory[]>(),
);

export function advisoriesFor(ecosystem: string, packageName: string): Advisory[] {
  return ADVISORY_INDEX.get(`${ecosystem}:${packageName.toLowerCase()}`) ?? [];
}
